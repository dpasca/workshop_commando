export type Grid = string[][];

// Parses a grid string: strips the 3-digit row numbers, splits cells on spaces.
export function parseGrid(text: string): Grid {
  return text
    .trim()
    .split("\n")
    .map((line) => line.trim().split(/\s+/).slice(1));
}
